"""Regenerate ``docs/DICTIONARY.md`` from ``dictionary/parameters.core.yaml``.

The generator is deterministic: iterating the YAML preserves insertion
order, so the output is stable across runs. Used by the ``gen-dictionary-doc``
pre-commit hook with ``--check``; a stale ``docs/DICTIONARY.md`` fails CI.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
DICT_PATH = REPO_ROOT / "dictionary" / "parameters.core.yaml"
TARGET = REPO_ROOT / "docs" / "DICTIONARY.md"


def _load_dictionary() -> dict[str, Any]:
    with DICT_PATH.open(encoding="utf-8") as f:
        data: dict[str, Any] = yaml.safe_load(f)
    return data


def _escape_cell(text: str) -> str:
    """Escape pipes and collapse newlines for a markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _fmt_unit(unit: str | None) -> str:
    return f"`{unit}`" if unit else "-"


def _fmt_range(pr: list[float] | None) -> str:
    if not pr:
        return "-"
    lo, hi = pr
    return f"`[{lo}, {hi}]`"


def _fmt_tier(tier: bool) -> str:
    return "yes" if tier else "-"


def _fmt_safety(sc: str) -> str:
    return f"`{sc}`" if sc != "none" else "-"


def _group_by_stage(
    params: dict[str, dict[str, Any]],
) -> list[tuple[str, list[str]]]:
    """Group keys by stage, in order of first appearance in the YAML."""
    seen: dict[str, list[str]] = {}
    for key, pr in params.items():
        stage = pr.get("stage", "unknown")
        seen.setdefault(stage, []).append(key)
    return list(seen.items())


def generate() -> str:
    data = _load_dictionary()
    version = data.get("dictionary_version", "?")
    params: dict[str, dict[str, Any]] = data["parameters"]

    lines: list[str] = [
        f"# Dictionary — parameters.core.yaml v{version}",
        "",
        "<!-- Generated by scripts/gen_dictionary_doc.py. Do not edit by hand. -->",
        "",
        "The core dictionary defines every parameter the engine consumes.",
        "Adding a **core** parameter is a minor engine release; extension",
        "parameters are declared inside a pack and validated by the engine",
        "without a version bump.",
        "",
        "For pack authoring see `PACK_FORMAT.md`; for how facts resolve see",
        "`RESOLUTION_POLICY.md`.",
        "",
        "Stages are listed in order of first appearance in",
        "`dictionary/parameters.core.yaml`.",
        "",
        "## Column reference",
        "",
        "- **Key**: the parameter identifier used in `facts/*.csv`.",
        "- **Shape**: one of `scalar`, `range`, `trapezoid`, `enum`,"
        " `enum_set`, `bool`, `rule`, `unknown`.",
        "- **Unit**: pint-compatible unit; `-` means dimensionless or not applicable.",
        "- **Phase set**: `none` (phase is not part of the fact key),"
        " `biological` (fact carries a biological phase), or `kc`"
        " (fact carries a crop-coefficient phase).",
        "- **Range**: physical sanity bounds, not agronomic judgements.",
        "- **Tier**: `yes` means the parameter is required for T2/T3 coverage.",
        "- **Safety**: a safety class other than `-` requires a `reviewed`"
        " status floor in `resolve_fact` and forbids `draft`/`imported`"
        " statuses.",
        "- **Description**: what the parameter means, in one sentence.",
        "",
    ]

    for stage, keys in _group_by_stage(params):
        lines.append(f"## Stage: `{stage}`")
        lines.append("")
        lines.append("| Key | Shape | Unit | Phase set | Range | Tier | Safety | Description |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for key in keys:
            pr = params[key]
            desc = _escape_cell(pr.get("description") or "")
            lines.append(
                "| "
                + " | ".join(
                    [
                        f"`{key}`",
                        f"`{pr['shape']}`",
                        _fmt_unit(pr.get("unit")),
                        f"`{pr['phase_set']}`",
                        _fmt_range(pr.get("physical_range")),
                        _fmt_tier(pr["tier_required"]),
                        _fmt_safety(pr["safety_class"]),
                        desc,
                    ]
                )
                + " |"
            )
        lines.append("")

    safety_params = [(k, pr) for k, pr in params.items() if pr["safety_class"] != "none"]
    if safety_params:
        lines.append("## Safety-critical parameters")
        lines.append("")
        lines.append(
            "These parameters carry a safety class other than `none`. They"
            " require a `reviewed` status floor and forbid `draft`/`imported`"
            " statuses; `resolve_fact` records the raise as"
            " `safety_min_status_raised`."
        )
        lines.append("")
        for key, pr in safety_params:
            rationale = _escape_cell(pr.get("rationale") or "(no rationale recorded)")
            lines.append(f"- **`{key}`** (`{pr['safety_class']}`): {rationale}")
        lines.append("")

    lines.extend(
        [
            "## See also",
            "",
            "- `PACK_FORMAT.md` — pack format and CSV codec",
            "- `RESOLUTION_POLICY.md` — how facts are resolved",
            "- `decisions/ADR-003-tiers-license-duplicates.md` — tiers and license gate",
            "- `decisions/ADR-004-resolution-policy.md` — full resolution policy",
            "",
        ]
    )

    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Regenerate docs/DICTIONARY.md from parameters.core.yaml."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if docs/DICTIONARY.md is out of sync; do not write.",
    )
    args = parser.parse_args()

    content = generate()

    if args.check:
        if not TARGET.exists():
            print(f"ERROR: {TARGET} does not exist", file=sys.stderr)
            return 1
        current = TARGET.read_text(encoding="utf-8")
        if current != content:
            print(
                f"ERROR: {TARGET.relative_to(REPO_ROOT)} is out of sync with"
                f" parameters.core.yaml.\nRun: python3 scripts/gen_dictionary_doc.py",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {TARGET.relative_to(REPO_ROOT)} is up to date")
        return 0

    TARGET.write_text(content, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
