"""Generate ``docs/CLIMATE_CATALOG.md`` and the shipped excluded list.

Run from the repo root:

    python3 scripts/gen_climate_catalog_doc.py
    python3 scripts/gen_climate_catalog_doc.py --check

The script reads ``docs/design/climate_catalog_v1.csv`` and writes:

- ``docs/CLIMATE_CATALOG.md`` — human-readable tables, one per kind.
- ``src/agri_core/catalog/_excluded_generated.py`` — ``EXCLUDED_PARAM_IDS``
  as a ``frozenset[str]``, shipped with the package.

With ``--check``, both files must match exactly; a drift fails CI. Both
outputs are deterministic (sorted ``param_id``), so a re-run leaves no diff.
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = REPO_ROOT / "docs" / "design" / "climate_catalog_v1.csv"
DOC_TARGET = REPO_ROOT / "docs" / "CLIMATE_CATALOG.md"
EXCLUDED_TARGET = REPO_ROOT / "src" / "agri_core" / "catalog" / "_excluded_generated.py"

_KIND_ORDER = ("computed", "input", "pack_value", "excluded")


def _load_rows() -> list[dict[str, str]]:
    with CSV_PATH.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _md_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip() or "-"


def _md_code(text: str) -> str:
    return f"`{text}`" if text else "-"


def generate_doc(rows: list[dict[str, str]]) -> str:
    parts: list[str] = [
        "# Climate parameter catalog",
        "",
        "<!-- Generated by scripts/gen_climate_catalog_doc.py from "
        "climate_catalog_v1.csv. Do not edit by hand. -->",
        "",
        "See `climate_catalog_v1_rationale.md` for the rationale and "
        "`decisions/ADR-012-climate-catalog.md` for the decision record.",
        "",
        f"Total rows: **{len(rows)}**.",
        "",
    ]
    for kind in _KIND_ORDER:
        subset = sorted(
            (r for r in rows if r["kind"] == kind),
            key=lambda r: r["param_id"],
        )
        if not subset:
            continue
        parts.append(f"## {kind.replace('_', ' ').capitalize()} ({len(subset)})")
        parts.append("")
        parts.append("| param_id | group | unit | status | milestone | method_ref | safety_tier |")
        parts.append("|---|---|---|---|---|---|---|")
        for r in subset:
            parts.append(
                "| "
                + " | ".join(
                    [
                        _md_code(r["param_id"]),
                        _md_cell(r["group"]),
                        _md_code(r["unit"]),
                        r["status"],
                        r["milestone"],
                        _md_cell(r["method_ref"]),
                        r["safety_tier"],
                    ]
                )
                + " |"
            )
        parts.append("")
    return "\n".join(parts)


def generate_excluded(rows: list[dict[str, str]]) -> str:
    excluded = sorted(r["param_id"] for r in rows if r["status"] == "excluded")
    lines: list[str] = [
        '"""GENERATED by scripts/gen_climate_catalog_doc.py. Do not edit by hand."""',
        "",
        "# fmt: off",
        "from __future__ import annotations",
        "",
        "EXCLUDED_PARAM_IDS: frozenset[str] = frozenset({",
    ]
    for pid in excluded:
        lines.append(f'    "{pid}",')
    lines.extend(["})", "", '__all__ = ["EXCLUDED_PARAM_IDS"]', ""])
    return "\n".join(lines)


def _write_or_check(target: Path, content: str, *, check: bool) -> bool:
    if check:
        if not target.exists():
            print(f"ERROR: {target.relative_to(REPO_ROOT)} missing", file=sys.stderr)
            return False
        if target.read_text(encoding="utf-8") != content:
            print(
                f"ERROR: {target.relative_to(REPO_ROOT)} out of sync. "
                f"Run: python3 scripts/gen_climate_catalog_doc.py",
                file=sys.stderr,
            )
            return False
        return True
    target.write_text(content, encoding="utf-8")
    print(f"wrote {target.relative_to(REPO_ROOT)}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Regenerate docs/CLIMATE_CATALOG.md and the shipped excluded list.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if either output is out of sync; do not write.",
    )
    args = parser.parse_args()

    rows = _load_rows()
    doc = generate_doc(rows)
    excluded = generate_excluded(rows)

    ok1 = _write_or_check(DOC_TARGET, doc, check=args.check)
    ok2 = _write_or_check(EXCLUDED_TARGET, excluded, check=args.check)
    if args.check:
        if ok1 and ok2:
            print("OK: both outputs are up to date")
            return 0
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
